/** Every rule above, as the Public Suffix List writes it ("co.uk", "*.sch.uk", "!www.ck"). */
export const PUBLIC_SUFFIX_RULES: ReadonlySet<string> = (() => {
  const rules = new Set<string>();
  let domain = "";
  for (const line of MULTI_LABEL.split("\n")) {
    const words = line.trim().split(" ").filter(Boolean);
    if (!words.length) continue;
    if (!line.startsWith(" ")) domain = words.shift() as string;
    for (const before of words) rules.add(`${before}.${domain}`);
  }
  return rules;
})();

/** The top-level domains whose rules of more than one label aren't all known here. */
export const NOT_LISTED_DOMAINS: readonly string[] = NOT_LISTED;
const NOT_LISTED_SET: ReadonlySet<string> = new Set(NOT_LISTED);

/** The most labels a rule has: no longer suffix is looked for. */
const MOST_LABELS = Math.max(...[...PUBLIC_SUFFIX_RULES].map((rule) => rule.split(".").length));

/**
 * How many labels of the public suffix `labels[0, end)` ends in: the
 * longest rule it matches (an exception wins, and is its rule less its
 * first label), else its last label alone (the List's default rule). Null
 * when its top-level domain is NOT_LISTED. `labels`: a host's, as the URL
 * parser gives it (lower case, ASCII).
 */
export function publicSuffixLength(labels: readonly string[], end = labels.length): number | null {
  if (end < 1 || NOT_LISTED_SET.has(labels[end - 1])) return null;
  let length = 1;
  let rest = labels[end - 1];
  for (let k = 2; k <= Math.min(end, MOST_LABELS); k++) {
    const rule = `${labels[end - k]}.${rest}`;
    if (PUBLIC_SUFFIX_RULES.has(`!${rule}`)) return k - 1;
    if (PUBLIC_SUFFIX_RULES.has(rule) || PUBLIC_SUFFIX_RULES.has(`*.${rest}`)) length = k;
    rest = rule;
  }
  return length;
}

// The URL parser's forms of an IP address: four decimal numbers, or brackets.
const IP_ADDRESS = /^(?:\d{1,3}(?:\.\d{1,3}){3}|\[.*\])$/;

/**
 * The registrable domain of `hostname` (lower case, ASCII, without a
 * trailing dot, as the URL parser gives it): its public suffix and one
 * label more ("en.wikipedia.org" → "wikipedia.org", "www.bbc.co.uk" →
 * "bbc.co.uk"); the hostname itself when it is a public suffix ("co.uk").
 * Null when it can't be told: an IP address, or a host under a top-level
 * domain whose rules aren't all known here (NOT_LISTED).
 */
export function registrableDomain(hostname: string): string | null {
  if (IP_ADDRESS.test(hostname)) return null;
  const labels = hostname.split(".");
  const suffix = publicSuffixLength(labels);
  return suffix === null ? null : labels.slice(Math.max(0, labels.length - suffix - 1)).join(".");
}
